package Code_With_Modassir;

public class CWH_22_The_Do_While_Loop {
    public static void main(String[] args) {
        int i = 1;
        do {
            System.out.println(i);
            i++;
        } while(i<=10);

        // Quick Quiz : Write a program to print first n natural number using do-while Loops
        int a = 1;
        int n = 45;
        do {
            System.out.println(a);
            a++;
        } while(a<=n);
    }
}
